import { useEffect, useRef, useState, type ReactNode } from "react";
import "./reveal.css";

type RevealVariant = "fade" | "clip" | "rise";

interface RevealProps {
  children: ReactNode;
  /** fade: soft opacity · clip: masked wipe · rise: gentle upward settle */
  variant?: RevealVariant;
  delay?: number;
  className?: string;
}

export default function Reveal({
  children,
  variant = "rise",
  delay = 0,
  className = "",
}: RevealProps) {
  const ref = useRef<HTMLDivElement | null>(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;

    // Reduced motion: content is simply present, no reveal choreography.
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      setVisible(true);
      return;
    }

    const io = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) {
            setVisible(true);
            io.disconnect();
          }
        }
      },
      { threshold: 0.12, rootMargin: "0px 0px -6% 0px" },
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      className={`reveal reveal-${variant}${visible ? " is-visible" : ""}${className ? ` ${className}` : ""}`}
      style={{ transitionDelay: `${delay}ms` }}
    >
      {children}
    </div>
  );
}
